#include "stm32f411xe.h"

void GPIO_Init(void) {
  // Enable GPIOC clock (Black Pill onboard LED is on PC13)
  RCC->AHB1ENR |= RCC_AHB1ENR_GPIOCEN;

  // Set PC13 as General Purpose Output (MODER bits: 01)
  GPIOC->MODER &= ~(3U << (13 * 2));
  GPIOC->MODER |= (1U << (13 * 2));

  // Turn LED off initially (PC13 is active-low on Black Pill)
  GPIOC->BSRR = (1U << 13);
}

void TIM2_Init(void) {
  // Enable TIM2 clock on APB1
  RCC->APB1ENR |= RCC_APB1ENR_TIM2EN;

  // Set Prescaler and Auto-Reload (Assumes default 16 MHz HSI clock)
  TIM2->PSC = 16000 - 1; // Counter ticks at 1 kHz (1 ms period)
  TIM2->ARR = 2000 - 1;   // Overflows every 1000 ms (1 Hz)

  // Clear the initial update flag generated by setting registers
  TIM2->SR &= ~TIM_SR_UIF;

  // Enable Update Interrupt in the timer
  TIM2->DIER |= TIM_DIER_UIE;

  // Enable TIM2 interrupt in the NVIC
  NVIC_EnableIRQ(TIM2_IRQn);
  NVIC_SetPriority(TIM2_IRQn, 2);

  // Start the counter
  TIM2->CR1 |= TIM_CR1_CEN;
}

// Interrupt Service Routine
void TIM2_IRQHandler(void) {
  // Check if the update interrupt flag is set
  if (TIM2->SR & TIM_SR_UIF) {
    // MUST clear the flag manually, or the ISR will re-trigger immediately
    TIM2->SR &= ~TIM_SR_UIF;

    // Toggle PC13
    GPIOC->ODR ^= (1U << 13);
  }
}

int main(void) {
  GPIO_Init();
  TIM2_Init();

  while (1) {
    // Waiting for Interrupt
    __WFI();
  }
}